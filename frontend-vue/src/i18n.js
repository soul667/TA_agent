// 中英双语：vue-i18n。语言偏好持久化在 localStorage('aa_lang')。
// 题目/诊断/反馈等“内容级”双语来自后端 *_en 字段，前端用 pick() 按语言选取。
import { createI18n } from 'vue-i18n'

export const LANG_KEY = 'aa_lang'

export function getLang() {
  // 抽查工作台默认中文，仍尊重用户已保存的英文偏好。
  return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'zh'
}

export function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang === 'en' ? 'en' : 'zh')
}

// 内容级字段选取：locale 为 en 且存在 en 字段时用英文，否则回退中文
export function pick(locale, obj, key) {
  if (!obj) return ''
  if (locale === 'en') {
    const v = obj[`${key}_en`]
    if (v !== undefined && v !== null && v !== '') return v
  }
  return obj[key]
}

// 后端错误 detail 目前为中文：EN 界面下按子串映射为英文（含数字捕获）
const BACKEND_EN = [
  [/访问码不属于该学号[^\s]*/, 'The access code does not match this student ID'],
  [/口令不正确|访问码不正确/, 'Invalid access code or token'],
  [/学号不存在/, 'Student ID not found'],
  [/问卷尚未生成/, 'The questionnaire has not been generated yet, please try again later'],
  [/问卷已更新到第 (\d+) 版（你提交的是第\s*(\d+)\s*版）/,
    'The questionnaire is now version v$1 (you submitted v$2). Refresh to answer the latest version'],
  [/答案格式有误[:：]\s*/, 'Invalid answer format: '],
  [/学号格式不正确[^（]*/, 'Invalid student ID format (expected 4-20 digits)'],
  [/该学生尚未提交问卷/, 'This student has not submitted the questionnaire yet'],
  [/作答编号不存在/, 'Attempt not found'],
  [/评价失败[:：]\s*/, 'Evaluation failed: '],
  [/问卷生成失败[:：]\s*/, 'Questionnaire generation failed: '],
  [/发布反馈时必须填写/, 'Feedback text is required when publishing'],
  [/decision 必须是/, 'decision must be confirmed or revised'],
  [/修订结论必须填写/, 'A revision requires the revised understanding level'],
  [/复核理由/, 'A review reason is required'],
  [/未认证|Not authenticated/, 'Authentication required'],
]

export function localizeBackendDetail(detail, locale) {
  const text = typeof detail === 'string' ? detail : String(detail || '')
  if (locale !== 'en' || !text) return text
  for (const [re, en] of BACKEND_EN) {
    if (re.test(text)) return text.replace(re, en)
  }
  return text
}

